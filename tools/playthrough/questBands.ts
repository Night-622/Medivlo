/**
 * Quest level bands (Claude 2, for Claude 3's quest-XP scaling, rules/curves.ts questXpMult): the level band of where
 * each quest takes place, as pure data for the sim (src/data/regions/hc/questBands.ts; the realm server can't import
 * src/world). Per class and quest: the median band in force (low, high) of the spawn zones the quest's walk passes
 * and the packs of the lairs it enters (out/act{1,2,3}-walks.json, so regenerate after any band change); a quest
 * several classes play (cc-*, heart-*) takes the median across them. Every quest id gets an entry: null where the
 * walk meets no fights (talk and town quests stay unscaled).
 *   ENTRY=tools/playthrough/questBands.ts OUT=<file> node tools/playthrough/build.mjs && node <file> <gen|check>
 *   gen    writes src/data/regions/hc/questBands.ts
 *   check  every quest id has an entry (also `checks.ts quest-bands`, in the world suite)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { Game, Registry, createNewGameState, type QuestDef } from '@/core';
import { spawnZones, zoneLevelAt } from '@/world/hc/spawns';
import { QUEST_BANDS } from '@/data/regions/hc/questBands';

type Zone = string | { id: string; level: [number, number] };
type Walks = Record<string, { quest: string; zones?: Zone[]; lairs?: string[] }[]>;
const mode = process.argv[2] === 'gen' ? 'gen' : 'check';

Game.set(createNewGameState());
Registry.load();
const quests = (Registry.all('quest') as QuestDef[]).map((q) => q.id as string);

const median = (xs: number[]) => { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.floor((s.length - 1) / 2)] : NaN; };
const lairBand = (inst: string, cls: string): [number, number] | null => {
  try { const z = spawnZones(inst)[0]; return z ? zoneLevelAt(z, () => false, cls) : null; } catch { return null; }
};

if (mode === 'gen') {
  const per = new Map<string, [number, number][]>(); // quest → one band per class that plays it
  for (const act of ['act1', 'act2', 'act3']) {
    const walks = JSON.parse(readFileSync(`tools/playthrough/out/${act}-walks.json`, 'utf8')) as Walks;
    for (const [cls, list] of Object.entries(walks)) for (const q of list) {
      const bands: [number, number][] = [];
      for (const z of q.zones ?? []) if (typeof z !== 'string') bands.push(z.level);
      for (const l of q.lairs ?? []) { const b = lairBand(l, cls); if (b) bands.push(b); }
      if (!bands.length) continue;
      per.set(q.quest, [...(per.get(q.quest) ?? []), [median(bands.map((b) => b[0])), median(bands.map((b) => b[1]))]]);
    }
  }
  const rows = [...quests].sort().map((id) => {
    const b = per.get(id);
    return `  '${id}': ${b ? `[${Math.round(median(b.map((x) => x[0])))}, ${Math.round(median(b.map((x) => x[1])))}]` : 'null'},`;
  });
  writeFileSync('src/data/regions/hc/questBands.ts', `/**
 * GENERATED by tools/playthrough/questBands.ts gen (Claude 2): do not edit. The level band [low, high] of where each
 * quest takes place (the zones its walk passes and the lairs it enters, bands in force for the classes that play it;
 * median across them), for Claude 3's quest-XP scaling. null: no fights on the way (left unscaled). Pure data: the
 * sim on the realm server reads it.
 */
export const QUEST_BANDS: Record<string, [number, number] | null> = {
${rows.join('\n')}
};
`);
  console.log(`wrote src/data/regions/hc/questBands.ts: ${quests.length} quests, ${per.size} banded, ${quests.length - [...quests].filter((q) => per.has(q)).length} null`);
} else {
  const missing = quests.filter((q) => !(q in QUEST_BANDS));
  const stale = Object.keys(QUEST_BANDS).filter((q) => !quests.includes(q));
  for (const q of missing.slice(0, 20)) console.log(`NO ENTRY ${q}`);
  for (const q of stale.slice(0, 20)) console.log(`NO SUCH QUEST ${q}`);
  const banded = Object.values(QUEST_BANDS).filter(Boolean).length;
  console.log(missing.length || stale.length ? `quest-bands: ${missing.length} quests without an entry, ${stale.length} entries for no quest (regenerate: questBands.ts gen)`
    : `quest-bands: all ${quests.length} quests have an entry (${banded} banded, ${quests.length - banded} unscaled)`);
  if (missing.length || stale.length) process.exitCode = 1;
}
