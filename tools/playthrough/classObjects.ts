/**
 * Class story objects (Claude 2, with Claude 1 and Claude 4, 2026-10-20): an object one campaign's quests use is
 * usable only in that campaign's world (`campaign.class`, set by the narrative engine on the authority and
 * replicated), so other classes' objects never take the [F] focus. Derived from the quest data, not the id prefix
 * (Morvane regions share the names `ash` and `storm` with schools, and realm optional-area finds belong to
 * everyone): an object is gated to the classes whose quests name it, unless a shared quest names it too; a
 * class-prefixed object (obj:<class>-…) no quest names is gated to its class.
 *   ENTRY=tools/playthrough/classObjects.ts OUT=<file> node tools/playthrough/build.mjs && node <file> <gen|check>
 *   gen    writes src/data/regions/hc/classObjects.gen.ts
 *   check  every space: for each class as host, no other class's object is usable and every one of its own is
 *          (also `checks.ts class-objects`)
 */
import { writeFileSync } from 'node:fs';
import { CHUNK_TILES, Game, Registry, createNewGameState, type QuestDef, type WorldObject } from '@/core';
import { AREAS, REALMS, instanceDef, spaceRuntime } from '@/world/hc/spaces';
import { SENTINELS } from '@/data/regions/hc/sentinels';

const mode = process.argv[2] === 'gen' ? 'gen' : 'check';
Game.set(createNewGameState());
Registry.load();
const CLASSES = [...new Set(AREAS.map((a) => a.className?.toLowerCase()).filter(Boolean))].sort() as string[];
const quests = Registry.all('quest') as QuestDef[];

/** every obj: id (or `prefix*`) each campaign's quests name in an objective */
const uses = new Map<string, Set<string>>(); // pattern → campaigns ('shared' included)
for (const q of quests) for (const st of q.stages) for (const o of st.objectives as Record<string, unknown>[]) {
  for (const v of [o.interact, o.reach]) {
    if (typeof v !== 'string' || !v.startsWith('obj:')) continue;
    if (!uses.has(v)) uses.set(v, new Set());
    uses.get(v)!.add(String(q.campaign ?? 'shared'));
  }
}
const campaignsOf = (id: string): Set<string> => {
  const out = new Set<string>();
  for (const [p, c] of uses) if (p === id || (p.endsWith('*') && id.startsWith(p.slice(0, -1)))) for (const x of c) out.add(x);
  return out;
};
const prefixClass = (id: string) => CLASSES.find((c) => id.startsWith(`obj:${c}-`));

/** the classes an object belongs to (empty: everyone's) */
function owners(id: string): string[] {
  const c = campaignsOf(id);
  if (c.has('shared') || [...c].some((x) => !CLASSES.includes(x))) return [];
  if (c.size) return [...c].sort();
  const p = prefixClass(id);
  return p ? [p] : [];
}

const inst = AREAS.flatMap((a) => [...[1, 2, 3].map((n) => `inst:${a.school}-${a.side}-lair-${n}`), `inst:${a.school}-${a.side}-cave`])
  .concat(['frost', 'gilded', 'storm', 'abbey', 'gloam', 'briar', 'ash', 'alder', 'road', 'marsh'].map((r) => `inst:${r}-cave`),
    ['inst:varric-barrow', 'inst:drowned-abbey', 'inst:concord-citadel'], SENTINELS.map((s) => s.inst))
  .filter((id) => instanceDef(id));
const spaces = [...REALMS.filter((r) => r.school).map((r) => r.space), 'concordia', ...inst];
const GATED_KINDS = new Set<WorldObject['kind']>(['interactable', 'sign', 'lore', 'lever']);
function objectsOf(space: string): WorldObject[] {
  const g = spaceRuntime(space).gen, out: WorldObject[] = [];
  for (let cy = 0; cy < Math.ceil(g.heightTiles / CHUNK_TILES); cy++) for (let cx = 0; cx < Math.ceil(g.widthTiles / CHUNK_TILES); cx++) out.push(...g.objects(cx, cy));
  return out;
}

if (mode === 'gen') {
  const table = new Map<string, string[]>();
  for (const space of spaces) for (const o of objectsOf(space)) {
    if (!o.id.startsWith('obj:') || !GATED_KINDS.has(o.kind)) continue;
    const who = owners(o.id);
    if (who.length) table.set(o.id, who);
  }
  const rows = [...table].sort(([a], [b]) => a.localeCompare(b)).map(([id, c]) => `  '${id}': [${c.map((x) => `'${x}'`).join(', ')}],`);
  writeFileSync('src/data/regions/hc/classObjects.gen.ts', `/**
 * GENERATED by tools/playthrough/classObjects.ts gen (Claude 2): do not edit. Story objects usable only in these
 * classes' campaigns (flag campaign.class), from the quests that name them. See src/world/hc/classGate.ts.
 */
export const CLASS_OBJECTS: Record<string, string[]> = {
${rows.join('\n')}
};
`);
  const multi = [...table].filter(([, c]) => c.length > 1);
  console.log(`wrote ${table.size} class objects; shared by more than one class: ${multi.map(([id, c]) => `${id} (${c.join(', ')})`).join('; ') || 'none'}`);
} else {
  // evaluate a `when` with campaign.class = host and every other flag (stage gates) treated as met
  type FC = { flag?: string; op?: string; value?: unknown; all?: FC[]; any?: FC[]; not?: FC };
  const ev = (c: FC | undefined, host: string): boolean => {
    if (!c) return true;
    if (c.all) return c.all.every((x) => ev(x, host));
    if (c.any) return c.any.some((x) => ev(x, host));
    if (c.not) return !ev(c.not, host);
    if (c.flag === 'campaign.class') return c.op === '!=' ? host !== c.value : host === c.value;
    return true;
  };
  let wrong = 0, missing = 0, checked = 0;
  for (const space of spaces) for (const o of objectsOf(space)) {
    if (!o.id.startsWith('obj:') || !GATED_KINDS.has(o.kind)) continue;
    const who = owners(o.id);
    checked++;
    for (const host of CLASSES) {
      const usable = ev(o.when as FC | undefined, host), should = !who.length || who.includes(host);
      if (usable && !should) { wrong++; if (wrong <= 8) console.log(`USABLE FOR ${host}: ${o.id} (${space}) belongs to ${who.join(', ')}`); }
      if (!usable && should) { missing++; if (missing <= 8) console.log(`HIDDEN FROM ${host}: ${o.id} (${space})`); }
    }
  }
  console.log(`${checked} story objects × ${CLASSES.length} hosts: ${wrong} usable by the wrong class, ${missing} hidden from their own`);
  if (wrong || missing) process.exitCode = 1;
  console.log(wrong || missing ? 'class-objects: FAIL' : 'class-objects: every class sees only its own story objects (and all of them)');
}
