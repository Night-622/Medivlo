/**
 * Generates src/data/dialogue/hc-epilogues.gen.ts from the "## Endings" tables in docs/lore/hollow-crown/06-outlines.
 * Each class × ending gives three slides: realm, mentor, nemesis (spared / destroyed). Run after editing an outline:
 *   node tools/narrative/gen-epilogues.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dir = path.join(root, 'docs/lore/hollow-crown/06-outlines');
const KEY = { 'Turning': 'turning', 'Unmaking': 'unmaking', 'Hollow Crown': 'crowned', 'First Chord': 'first-chord' };
const curly = (s) => s.replace(/(\w)'(\w)/g, '$1’$2').replace(/'(\w)/g, '‘$1').replace(/(\w)'/g, '$1’');
const sentence = (s) => {
  let t = curly(s.trim().replace(/\s*\((Devoted|Trusted|Friendly)\)/g, '').replace(/\*\*/g, ''));
  t = t[0].toUpperCase() + t.slice(1);
  return /[.!?”’)]$/.test(t) ? t : t + '.';
};
// names from the campaign table (classes.ts rows): [id, name, school, side, realm, start, sibling, mentor, nemesis, …]
const rows = fs.readFileSync(path.join(root, 'src/narrative/engine/classes.ts'), 'utf8').matchAll(/^  \['([a-z]+)', '[^']+', '[a-z]+', '[a-z]+', '[^']+', '[^']+', '[a-z]+', '([^']+)', '([^']+)'/gm);
const NAMES = {};
for (const r of rows) NAMES[r[1]] = { mentor: r[2], nemesis: r[3] };
const PRONOUN = /^(his|her|their|its|a|an|the|one|no|nobody|she|he|they|there|it|every|all|both)\b/i;
/** a cell that opens with a bare verb ("stokes the Kiln") gets its subject: the person's name */
const subject = (raw, who) => (/^[a-z]/.test(raw.trim()) && !PRONOUN.test(raw.trim()) ? `${who} ${raw.trim()}` : raw);
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'README.md')) {
  let cls = null, inEnd = false;
  for (const line of fs.readFileSync(path.join(dir, f), 'utf8').split('\n')) {
    const h = line.match(/^# ([A-Z]+):/); if (h) { cls = h[1].toLowerCase(); continue; }
    if (/^## Endings/.test(line)) { inEnd = true; continue; }
    if (/^## /.test(line)) { inEnd = false; continue; }
    if (!inEnd || !cls) continue;
    const m = line.match(/^\| (Turning|Unmaking|Hollow Crown|First Chord) \| (.+) \| (.+) \| (.+) \|\s*$/);
    if (!m) continue;
    const [spared, destroyed] = m[4].split(' / ');
    const nm = NAMES[cls] ?? { mentor: '', nemesis: '' };
    (out[cls] ??= {})[KEY[m[1]]] = {
      realm: sentence(m[2]), mentor: sentence(subject(m[3], nm.mentor)),
      spared: sentence(subject(spared, nm.nemesis)), destroyed: sentence(subject(destroyed ?? spared, nm.nemesis)),
    };
  }
}
const n = Object.keys(out).length;
if (n !== 24) { console.error('expected 24 classes, got', n, Object.keys(out)); process.exit(1); }
const ts = `/* GENERATED by tools/narrative/gen-epilogues.mjs from the 06-outlines "Endings" tables. Do not edit by hand. */\n` +
  `export type EndingId = 'turning' | 'unmaking' | 'crowned' | 'first-chord';\n` +
  `export interface EpilogueSlides { realm: string; mentor: string; spared: string; destroyed: string }\n` +
  `export const CLASS_EPILOGUES: Record<string, Record<EndingId, EpilogueSlides>> = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'src/narrative/engine/epilogues.gen.ts'), ts);
console.log('wrote 24 classes × 4 endings');
