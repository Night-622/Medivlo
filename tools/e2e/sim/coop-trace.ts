/**
 * Co-op positional trace (Claude 5 for Claude 3, 2026-10-21): a melee hero with a ranged partner against the melee
 * hero's boss, every 0.5 s: the boss's position, target (threat) and wind-up, each hero's distance and reach, and why a
 * hero out of reach is out of reach (dodging, leaving a zone, knocked / dashing, held, walking in, standing). Solo is
 * traced too for comparison. Gear: typical build kit.
 *   node tools/e2e/sim/run.mjs coop-trace [melee] [ranged] [level]   (defaults swordsman ranger 14)
 *   BOT=a|b|c (default b: chase; a: the builds Bot; c: chase + ranged hold)   → tools/e2e/out/coop-trace.md
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { seedOf, typicalBuild } from './builds-make';
import { bossFor, type Level } from './builds-run';
import { runParty, type BotOpts, type TraceRow } from './coop-party';

const [melee = 'swordsman', ranged = 'ranger', lv = '14'] = process.argv.slice(3);
const L = Number(lv) as Level;
const BOT: BotOpts = process.env.BOT === 'a' ? { chase: false } : process.env.BOT === 'c' ? { chase: true, holdRanged: true } : { chase: true };
const boss = bossFor(melee, L);

function trace(classes: string[]): { rows: TraceRow[]; secs: number; won: boolean } {
  const rows: TraceRow[] = [];
  const r = runParty(classes.map((c) => typicalBuild(c, L).save), [{ creature: boss.id, level: L, x: 220, y: 0 }], seedOf('coop', melee, L, 'boss', 0), 600, 1, undefined, { ...BOT, trace: rows });
  return { rows, secs: r.secs, won: r.won };
}
const summary = (rows: TraceRow[], cls: string) => {
  const hs = rows.map((r) => r.heroes.find((h) => h.cls === cls)).filter((h): h is TraceRow['heroes'][number] => !!h);
  const why: Record<string, number> = {};
  for (const h of hs) why[h.why] = (why[h.why] ?? 0) + 1;
  const targeted = rows.filter((r) => r.foe.target === cls).length;
  return `${cls}: ${Object.entries(why).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${((v / hs.length) * 100).toFixed(0)}%`).join(', ')}; boss targets it ${((targeted / rows.length) * 100).toFixed(0)}% of the time; mean distance ${(hs.reduce((a, h) => a + h.d, 0) / Math.max(1, hs.length)).toFixed(0)} px (reach ${hs[0]?.reach ?? '?'})`;
};

const solo = trace([melee]), duo = trace([melee, ranged]);
// threat flips: how often the boss's target changes
const flips = (rows: TraceRow[]) => rows.reduce((a, r, i) => a + (i && r.foe.target !== rows[i - 1].foe.target ? 1 : 0), 0);
const md: string[] = [`# Co-op trace: ${melee} + ${ranged} vs ${boss.name} (L${L})`, '', `Generated by tools/e2e/sim/coop-trace.ts, bot ${process.env.BOT ?? 'b'} (${JSON.stringify({ ...BOT, trace: undefined })}). Samples every 0.5 s.`, '',
  '## Totals', '', `- solo: ${solo.won ? 'won' : 'lost'} in ${solo.secs} s. ${summary(solo.rows, melee)}`,
  `- party: ${duo.won ? 'won' : 'lost'} in ${duo.secs} s. ${summary(duo.rows, melee)}`, `- party: ${summary(duo.rows, ranged)}`,
  `- boss target changes: ${flips(duo.rows)} in ${duo.rows.length} samples (party), ${flips(solo.rows)} (solo)`, '',
  '## Party timeline', '', `| t (s) | boss x, y | boss target | boss wind-up | ${melee} x, y | dist / reach | ${melee} state | ${ranged} x, y | dist | ${ranged} state |`, '|---|---|---|---|---|---|---|---|---|---|'];
for (const r of duo.rows) {
  const m = r.heroes.find((h) => h.cls === melee), g = r.heroes.find((h) => h.cls === ranged);
  md.push(`| ${r.t} | ${r.foe.x}, ${r.foe.y} | ${r.foe.target ?? '—'} | ${r.foe.windup ?? ''} | ${m ? `${m.x}, ${m.y}` : 'down'} | ${m ? `${m.d} / ${m.reach}` : ''} | ${m?.why ?? ''} | ${g ? `${g.x}, ${g.y}` : 'down'} | ${g?.d ?? ''} | ${g?.why ?? ''} |`);
}
mkdirSync('tools/e2e/out', { recursive: true });
writeFileSync('tools/e2e/out/coop-trace.md', md.join('\n'));
