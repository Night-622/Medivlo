/**
 * Co-op A/B (Claude 5 for Claude 1, 2026-10-21): why do melee and healers deal less in parties than solo predicts? Each
 * line-up from coop-balance.ts fights its boss with bot A (as before: never walks toward its target, the boss comes to
 * it), bot B (chase: walks into basic-attack reach) and bot C (B, and ranged heroes stop kiting while an ally stands),
 * alone and as a party, at the gear-curve kits. Per member: time
 * out of reach, damage share vs the share its solo rate predicts, healing given to the others.
 *   node tools/e2e/sim/run.mjs coop-ab      → tools/e2e/out/coop-ab.md   (FIGHTS=n, default 2)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import type { CharacterSave } from '@/systems/rules/types';
import { seedOf, typicalBuild } from './builds-make';
import { bossFor, LEVELS, type Level } from './builds-run';
import { runParty, type BotOpts, type PartyResult } from './coop-party';
import { questsOf, runClass } from './gear-curve-walk';

const FIGHTS = Number(process.env.FIGHTS) || 2;
const PARTIES: string[][] = [
  ['arcanist', 'swordsman'], ['monk', 'ranger', 'skald'], ['knight', 'arcanist', 'cantor'], ['juggernaut', 'stormlancer', 'hedgewitch', 'bard'],
  ['warden', 'duskweaver', 'samurai', 'falconer'], ['huntsman', 'bard'], ['warden', 'cantor'],
];
const BOTS: [string, BotOpts][] = [['A (no chase)', { chase: false }], ['B (chase)', { chase: true }], ['C (chase, ranged hold)', { chase: true, holdRanged: true }]];
const t0 = Date.now();
const saves = new Map<string, CharacterSave>();
for (const cls of [...new Set(PARTIES.flat())]) {
  const own = await questsOf(cls);
  runClass(cls, 101, own, LEVELS, (L, pl) => { const s = typicalBuild(cls, L).save; s.equipment = structuredClone(pl.s.equipment); saves.set(`${cls}@${L}`, s); });
}
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);
const fight = (party: string[], L: Level, bot: BotOpts, host = party[0]): PartyResult[] => Array.from({ length: FIGHTS }, (_, f) =>
  runParty(party.map((c) => saves.get(`${c}@${L}`) ?? typicalBuild(c, L).save), [{ creature: bossFor(host, L).id, level: L, x: 220, y: 0 }], seedOf('coop', host, L, 'boss', f), 600, 1, undefined, bot));
const won = (rs: PartyResult[]) => mean(rs.filter((r) => r.won).map((r) => r.secs));

const md: string[] = ['# Co-op A/B: bot or game?', '', `Generated by tools/e2e/sim/coop-ab.ts (${FIGHTS} seeds). A = the builds Bot (moves only to kite, dodge or leave a zone); B = A + walks into basic-attack reach; C = B + ranged heroes hold their ground while an ally stands. ` +
  'Out of reach = share of fight time with the target beyond basic-attack reach. Share = the member\'s part of party damage; predicted = its solo damage rate\'s part (solo time vs the same boss, party size 1).', ''];
const agg: Record<string, { bot: string; cls: string; reach: number[]; ratio: number[]; healed: number[] }> = {};
for (const party of PARTIES) for (const L of LEVELS) {
  md.push(`### ${party.join(' + ')} · L${L} · ${bossFor(party[0], L).name}`, '', '| bot | party time | member | alone (s) | out of reach alone | out of reach in party | share | predicted | healing to others |', '|---|---|---|---|---|---|---|---|---|');
  for (const [name, bot] of BOTS) {
    const res = fight(party, L, bot), alone = party.map((c) => fight([c], L, bot, party[0]));
    const soloSecs = alone.map(won), rate = soloSecs.map((s) => (s > 0 ? 1 / s : 0)), rTot = rate.reduce((a, b) => a + b, 0) || 1;
    const dealt = party.map((_, i) => mean(res.map((r) => r.members[i].dealt))), dTot = dealt.reduce((a, b) => a + b, 0) || 1;
    party.forEach((c, i) => {
      const reachP = mean(res.map((r) => r.members[i].outOfReach / Math.max(1, r.members[i].fightSecs)));
      const reachS = mean(alone[i].map((r) => r.members[0].outOfReach / Math.max(1, r.members[0].fightSecs)));
      const share = dealt[i] / dTot, want = rate[i] / rTot, healed = mean(res.map((r) => r.members[i].healedOthers));
      md.push(`| ${name} | ${i ? '' : won(res).toFixed(0) + ' s'} | ${c} | ${soloSecs[i].toFixed(0)} | ${(reachS * 100).toFixed(0)}% | ${(reachP * 100).toFixed(0)}% | ${(share * 100).toFixed(0)}% | ${(want * 100).toFixed(0)}% | ${healed.toFixed(0)} |`);
      const a = (agg[`${name}|${c}`] ??= { bot: name, cls: c, reach: [], ratio: [], healed: [] });
      a.reach.push(reachP); if (want > 0) a.ratio.push(share / want); a.healed.push(healed);
    });
  }
  md.push('');
}
const lines = Object.values(agg).sort((a, b) => a.cls.localeCompare(b.cls) || a.bot.localeCompare(b.bot));
md.splice(3, 0, '## By class (all line-ups and levels)', '', '| class | bot | out of reach in party | share ÷ predicted | healing to others / fight |', '|---|---|---|---|---|',
  ...lines.map((a) => `| ${a.cls} | ${a.bot} | ${(mean(a.reach) * 100).toFixed(0)}% | ${mean(a.ratio).toFixed(2)} | ${mean(a.healed).toFixed(0)} |`), '');
mkdirSync('tools/e2e/out', { recursive: true });
writeFileSync('tools/e2e/out/coop-ab.md', md.join('\n'));
for (const a of lines) console.log(`${a.cls.padEnd(12)} ${a.bot.padEnd(13)} out of reach ${(mean(a.reach) * 100).toFixed(0).padStart(3)}% · share÷predicted ${mean(a.ratio).toFixed(2)} · healing to others ${mean(a.healed).toFixed(0)}`);
console.log(`report tools/e2e/out/coop-ab.md · run time ${((Date.now() - t0) / 1000).toFixed(1)} s`);
