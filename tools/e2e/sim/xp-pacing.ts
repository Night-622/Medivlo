/**
 * XP pacing against the zones' bands (Claude 5 for Claude 1, 2026-10-21): the gear-curve typical player's walk
 * (gear-curve-walk.ts: Claude 2's walk-export quest order, its zones, lairs, optional ruins / caves, quest XP), solo and
 * as a duo (party XP: every hero near a kill gets the full XP, packs and lair waves are ×spawnCountMult bigger, bosses
 * and quest kills stay single). For each quest with zones: the hero's level as it starts vs those zones' band (Claude
 * 2's walk export) — under = below the band's low end − 1 (a forced grind), over = above its high end + 2 (no challenge).
 *   node tools/e2e/sim/run.mjs xp-pacing [classId…]      → tools/e2e/out/xp-pacing.md   (OPT=0 skips optional sites)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { CLASS_SCHOOL } from '@/core/constants';
import { ACT_BANDS } from '@/systems/rules/curves';
import { questsOf, runClass } from './gear-curve-walk';

const args = process.argv.slice(3);
const CLASSES = args.length ? args : Object.keys(CLASS_SCHOOL);
const PARTIES = [1, 2] as const;
type WalkZone = string | { id: string; level: [number, number] };
type Walk = Record<string, { quest: string; zones?: WalkZone[]; expected?: number }[]>;
const walk: Walk = {}, actOf = new Map<string, number>();
(['act1', 'act2', 'act3'] as const).forEach((a, k) => {
  for (const [cls, list] of Object.entries(JSON.parse(readFileSync(`tools/playthrough/out/${a}-walks.json`, 'utf8')) as Walk)) {
    (walk[cls] ??= []).push(...list);
    for (const w of list) actOf.set(`${cls}|${w.quest}`, k + 1);
  }
});
const bandOf = (cls: string, q: string): [number, number] | null => {
  const zs = (walk[cls]?.find((w) => w.quest === q)?.zones ?? []).filter((z): z is { id: string; level: [number, number] } => typeof z !== 'string');
  return zs.length ? [Math.min(...zs.map((z) => z.level[0])), Math.max(...zs.map((z) => z.level[1]))] : null;
};
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);

interface Row { cls: string; n: number; actEnd: number[]; under: number; over: number; quests: number; delta: number[]; byAct: { under: number; over: number; n: number; delta: number[] }[]; worst: string[] }
const rows: Row[] = [];
const t0 = Date.now();
for (const cls of CLASSES) {
  const own = await questsOf(cls);
  for (const n of PARTIES) {
    const at: [string, number][] = [];
    const run = runClass(cls, 101, own, [], undefined, (q, L) => at.push([q, L]), { party: n });
    const row: Row = { cls, n, actEnd: [], under: 0, over: 0, quests: 0, delta: [], byAct: [1, 2, 3].map(() => ({ under: 0, over: 0, n: 0, delta: [] })), worst: [] };
    // act ends: the hero's level at the first quest of the next act (the campaign's end for Act III)
    for (const act of [1, 2]) { const first = at.find(([q]) => actOf.get(`${cls}|${q}`) === act + 1); row.actEnd.push(first ? first[1] : NaN); }
    row.actEnd.push(run.end);
    const off: [number, string][] = [];
    for (const [q, L] of at) {
      const b = bandOf(cls, q), act = actOf.get(`${cls}|${q}`) ?? 0;
      if (!b || !act) continue;
      const d = L - (b[0] + b[1]) / 2, A = row.byAct[act - 1];
      row.quests++; A.n++; row.delta.push(d); A.delta.push(d);
      if (L < b[0] - 1) { row.under++; A.under++; off.push([L - b[0], `${q.slice(6)} L${L.toFixed(1)} vs ${b[0]}–${b[1]}`]); }
      if (L > b[1] + 2) { row.over++; A.over++; off.push([L - b[1], `${q.slice(6)} L${L.toFixed(1)} vs ${b[0]}–${b[1]}`]); }
    }
    row.worst = off.sort((a, b) => Math.abs(b[0]) - Math.abs(a[0])).slice(0, 3).map((x) => x[1]);
    rows.push(row);
    console.log(`${cls.padEnd(12)} ${n === 1 ? 'solo' : 'duo '} act ends ${row.actEnd.map((x) => 'L' + x.toFixed(1)).join(' / ')} · vs band mid ${row.byAct.map((a) => (mean(a.delta) >= 0 ? '+' : '') + mean(a.delta).toFixed(1)).join(' / ')} · under ${row.under} · over ${row.over} of ${row.quests}`);
  }
}

const md: string[] = ['# XP pacing vs zone bands', '', `Generated by tools/e2e/sim/xp-pacing.ts (the gear-curve typical player's walk, Claude 2's walk exports and bands as they are in the tree now). ` +
  `Act bands (curves.ts ACT_BANDS): ${Object.values(ACT_BANDS).map((b) => `L${b[0]}–${b[1]}`).join(', ')}. Under = hero below the quest zones' low end − 1; over = above their high end + 2. ` +
  'Duo: party XP is not split (every hero near a kill gets the full XP); packs and lair waves are 1.35× bigger.', ''];
const agg = (n: number, f: (r: Row) => number) => mean(rows.filter((r) => r.n === n).map(f));
md.push('## Summary', '', '| | act I end | act II end | act III end | hero − band mid, act I / II / III | quests under-levelled | quests over-levelled |', '|---|---|---|---|---|---|---|');
for (const n of PARTIES) {
  const rs = rows.filter((r) => r.n === n), q = rs.reduce((a, r) => a + r.quests, 0);
  md.push(`| ${n === 1 ? 'solo' : 'duo'} | L${agg(n, (r) => r.actEnd[0]).toFixed(1)} | L${agg(n, (r) => r.actEnd[1]).toFixed(1)} | L${agg(n, (r) => r.actEnd[2]).toFixed(1)} | ${[0, 1, 2].map((a) => { const v = mean(rs.flatMap((r) => r.byAct[a].delta)); return (v >= 0 ? '+' : '') + v.toFixed(1); }).join(' / ')} | ${rs.reduce((a, r) => a + r.under, 0)} of ${q} (${[0, 1, 2].map((a) => rs.reduce((s, r) => s + r.byAct[a].under, 0)).join(' / ')}) | ${rs.reduce((a, r) => a + r.over, 0)} of ${q} (${[0, 1, 2].map((a) => rs.reduce((s, r) => s + r.byAct[a].over, 0)).join(' / ')}) |`);
}
md.push('', '## By class', '', '| class | party | act ends | hero − band mid (I / II / III) | under | over | worst quests |', '|---|---|---|---|---|---|---|');
for (const r of rows) md.push(`| ${r.cls} | ${r.n === 1 ? 'solo' : 'duo'} | ${r.actEnd.map((x) => 'L' + x.toFixed(1)).join(' / ')} | ${r.byAct.map((a) => (mean(a.delta) >= 0 ? '+' : '') + mean(a.delta).toFixed(1)).join(' / ')} | ${r.under} | ${r.over} | ${r.worst.join('; ')} |`);
mkdirSync('tools/e2e/out', { recursive: true });
writeFileSync('tools/e2e/out/xp-pacing.md', md.join('\n'));
console.log(`report tools/e2e/out/xp-pacing.md · run time ${((Date.now() - t0) / 1000).toFixed(1)} s`);
