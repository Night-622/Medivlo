/**
 * Regenerate src/data/enemies/hc/bodies.gen.ts (Claude 3): the drawn width of every creature body, measured from the
 * art (alpha-trimmed frame 0; code-drawn bodies estimated from their arch/tier frame). creatures.ts sizes each
 * hitbox from it. Run after art changes: node tools/e2e/sim/run.mjs bodies-gen
 */
import { writeFileSync } from 'fs';
import path from 'path';
import { bodyWidths } from './hitboxes-art';

const widths = [...bodyWidths()].sort(([a], [b]) => a.localeCompare(b));
const lines = widths.map(([id, { w, est }]) => `  '${id}': ${w},${est ? ' // estimated' : ''}`);
const out = `/* GENERATED by tools/e2e/sim/bodies-gen.ts from public/art (alpha-trimmed frame 0). Do not edit by hand. */
/** Drawn width in px of each creature body's art: creatures.ts sizes hitboxes to ~85% of it. */
export const HC_BODY_WIDTH: Record<string, number> = {
${lines.join('\n')}
};
`;
writeFileSync(path.join(process.cwd(), 'src/data/enemies/hc/bodies.gen.ts'), out);
console.log(`bodies.gen.ts: ${widths.length} bodies (${widths.filter(([, x]) => x.est).length} estimated)`);
