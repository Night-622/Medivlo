/**
 * The first ten minutes (Claude 5 for Claude 1, 2026-10-21): does the starter kit, plus the first perk points, kill the
 * class's first realm packs comfortably? For every class, the first 3 fights on its own route (Claude 2's Act I walk
 * export: camps and patrols as packs, ambient zones in groups of up to 3, at their band's level, with their creature
 * pool), each from full health, fought by builds-fight.ts's bot with the starting 5 health draughts and 2 Ember tonics:
 *   L1: the starter kit (no points) · L2: each of the 9 first picks · L3: two points down the first spell path.
 * Flags: a death, a fight over 30 s, or potions drunk in a first fight.
 *   node tools/e2e/sim/run.mjs first-minutes [classId…]      → tools/e2e/out/first-minutes.md
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { CLASS_SCHOOL } from '@/core/constants';
import { allNodes } from '@/systems/rules/tree';
import type { CharacterSave } from '@/systems/rules/types';
import { spawnZones } from '@/world/hc/spawns';
import { runFight, type FightResult, type Spawn } from './builds-fight';
import { freshBuild, seedOf } from './builds-make';

const SLOG_S = 30;
const args = process.argv.slice(3);
const CLASSES = args.length ? args : Object.keys(CLASS_SCHOOL);
type WalkZone = string | { id: string; level: [number, number]; cap: number; elite?: boolean };
const walk = JSON.parse(readFileSync('tools/playthrough/out/act1-walks.json', 'utf8')) as Record<string, { quest: string; zones?: WalkZone[] }[]>;
const realmOf = (id: string) => /^(?:camp|patrol|zone|guard|pack):([a-z]+)-/.exec(id)?.[1];
const poolOf = (id: string): string[] => { const r = realmOf(id); try { return r ? spawnZones(`realm:${r}`).find((z) => z.id === id)?.pool ?? [] : []; } catch { return []; } };
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);

/** the first 3 fights on the class's route */
function firstFights(cls: string): { label: string; spawns: Spawn[] }[] {
  const out: { label: string; spawns: Spawn[] }[] = [];
  for (const w of walk[cls] ?? []) for (const z of w.zones ?? []) {
    if (out.length >= 3 || typeof z === 'string') continue;
    const pool = poolOf(z.id).length ? poolOf(z.id) : [`bx_${CLASS_SCHOOL[cls]}_0`];
    const n = Math.min(3, z.cap), lv = Math.round((z.level[0] + z.level[1]) / 2);
    out.push({ label: `${z.id} (${n} × L${lv})`, spawns: Array.from({ length: n }, (_, k) => ({ creature: pool[k % pool.length], level: lv, x: 150 + k * 30, y: -40 + k * 40, elite: !!z.elite && k === 0 })) });
  }
  return out;
}

interface Run { cls: string; setup: string; L: number; fights: { label: string; r: FightResult }[] }
const runs: Run[] = [];
const t0 = Date.now();
for (const cls of CLASSES) {
  const fights = firstFights(cls);
  const play = (setup: string, s: CharacterSave) => runs.push({ cls, setup, L: s.level, fights: fights.map((f, k) => ({ label: f.label, r: runFight(s, f.spawns, seedOf('first', cls, setup, k), 120) })) });
  play('starter kit', freshBuild(cls, 1).save);
  const nodes = allNodes(cls), name = (id: string) => nodes.find((n) => n.id === id)?.name ?? id;
  for (const id of ['sp_p0m1', 'sp_p1m1', 'sp_p2m1', 'sk_p0a', 'sk_p1a', 'sk_p2a', 'up_p0a', 'up_p1a', 'up_p2a']) {
    const s = freshBuild(cls, 2).save;
    s.tree = { [id]: 1 };
    const spell = nodes.find((n) => n.id === id)?.grantsSpell;
    if (spell) s.hotbar[3] = spell;
    play(`L2 first pick: ${name(id)}`, s);
  }
  const s3 = freshBuild(cls, 3).save;
  s3.tree = { sp_p0m1: 1, sp_p0m2: 1 };
  s3.hotbar[3] = nodes.find((n) => n.id === 'sp_p0m1')?.grantsSpell ?? null;
  play(`L3: ${name('sp_p0m1')} + ${name('sp_p0m2')}`, s3);
  const mine = runs.filter((r) => r.cls === cls), all = mine.flatMap((r) => r.fights.map((f) => f.r));
  console.log(`${cls.padEnd(12)} ${fights.length} fights · deaths ${all.filter((r) => !r.won).length} · slowest ${Math.max(...all.map((r) => r.secs))} s · mean ${mean(all.map((r) => r.secs)).toFixed(1)} s · potions ${all.reduce((a, r) => a + r.potions, 0)} · min HP left ${Math.min(...all.map((r) => r.hpLeft))}%`);
}

// ───────────── report ─────────────
const md: string[] = ['# The first ten minutes', '', 'Generated by tools/e2e/sim/first-minutes.ts. Each class’s first 3 fights on its own route, from full health, by the fight bot with the starting potions. ' +
  `Setups: the starter kit at L1, each of the 9 first picks at L2, and two points down the first spell path at L3. Flags: a death, a fight over ${SLOG_S} s, potions drunk.`, ''];
const flagged: string[] = [];
for (const r of runs) for (const f of r.fights) {
  const why = [!f.r.won ? 'died' : '', f.r.secs > SLOG_S ? `${f.r.secs} s` : '', f.r.potions ? `${f.r.potions} potion(s)` : ''].filter(Boolean);
  if (why.length) flagged.push(`- **${r.cls}**, ${r.setup}, ${f.label}: ${why.join(', ')} (HP left ${f.r.hpLeft}%)`);
}
md.push('## Flags', '', ...(flagged.length ? flagged : ['- none']), '');
md.push('## By class', '', '| class | first fights | deaths | slowest fight | mean fight | potions | lowest HP left | starter kit alone (L1): times |', '|---|---|---|---|---|---|---|---|');
for (const cls of CLASSES) {
  const mine = runs.filter((r) => r.cls === cls), all = mine.flatMap((r) => r.fights.map((f) => f.r)), st = mine.find((r) => r.setup === 'starter kit')!;
  md.push(`| ${cls} | ${st.fights.map((f) => f.label).join('; ')} | ${all.filter((r) => !r.won).length} | ${Math.max(...all.map((r) => r.secs))} s | ${mean(all.map((r) => r.secs)).toFixed(1)} s | ${all.reduce((a, r) => a + r.potions, 0)} | ${Math.min(...all.map((r) => r.hpLeft))}% | ${st.fights.map((f) => `${f.r.secs} s / ${f.r.hpLeft}%`).join(', ')} |`);
}
mkdirSync('tools/e2e/out', { recursive: true });
writeFileSync('tools/e2e/out/first-minutes.md', md.join('\n'));
console.log(`${flagged.length} flags · report tools/e2e/out/first-minutes.md · run time ${((Date.now() - t0) / 1000).toFixed(1)} s`);
