/**
 * Boss check at a typical player's gear (Claude 5 for Claude 1, 2026-10-21). For each class: its lair-2 boss at L8, nemesis
 * at L14 and Act III form at L34 (builds-run.ts bossFor), fought with the kit the gear-curve typical player is actually
 * wearing when it reaches that level (gear-curve-walk.ts, one kit per seed), on the typical build's tree and hotbar.
 * Reference: the same fight in the builds suite's typical gear (keptUpTier, no affixes). A boss is a wall for a typical
 * player when it wins < 2 of 3 fights, or takes > 2× the reference time, or > 300 s.
 *   node tools/e2e/sim/run.mjs boss-check [classId…]      → tools/e2e/out/boss-check.md
 *   SEEDS=n gear-curve kits per level (default 3) · FIGHTS=n fight seeds per kit (default 2)
 *   node tools/e2e/sim/run.mjs boss-check gate   pre-deploy gate: every boss won at typical gear, 0 deaths, every win
 *     ≤ 300 s (or its documented allowance in ALLOW), no crash; "N/M passed", exit code 1 on a failure
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { CLASS_SCHOOL } from '@/core/constants';
import type { CharacterSave } from '@/systems/rules/types';
import { runFight, type FightResult } from './builds-fight';
import { seedOf, typicalBuild } from './builds-make';
import { bossFor, LEVELS, type Level } from './builds-run';

const BOSS_SLOT_NAME: Record<number, string> = { 8: 'lair-2', 14: 'nemesis', 34: 'Act III' };
import { check, tally } from './features-harness';
import { gearScore } from './gear-curve-model';
import { questsOf, runClass } from './gear-curve-walk';

const SEEDS = Number(process.env.SEEDS) || 3;
const FIGHTS = Number(process.env.FIGHTS) || 2;
const GATE = process.argv.slice(3).includes('gate');
const args = process.argv.slice(3).filter((a) => a !== 'gate');
const CLASSES = args.length ? args : Object.keys(CLASS_SCHOOL);
const WALL_SECS = 300;
/** documented per-boss time allowances for the gate ('<class>:<level>' → { secs, why }). None today: Torvald was cut to ×0.62
 * HP at the source (Claude 3, 2026-10-21) instead of an allowance; the healer's Herald of Noon sits at ~204 s. */
const ALLOW: Record<string, { secs: number; why: string }> = {};

interface Cell { cls: string; L: Level; boss: string; ref: FightResult; refScore: number; fights: FightResult[]; scores: number[]; ilvl: number[] }
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);
const fight = (save: CharacterSave, cls: string, L: Level, k: number) => runFight(save, [{ creature: bossFor(cls, L).id, level: L, x: 200, y: 0 }], k ? seedOf(cls, L, 'boss', k) : seedOf(cls, L, 'boss')); // k 0 = the builds suite's own boss seed

const cells: Cell[] = [];
const t0 = Date.now();
for (const cls of CLASSES) {
  const own = await questsOf(cls);
  const kits: Record<number, CharacterSave['equipment'][]> = {};
  for (let k = 0; k < SEEDS; k++) runClass(cls, 101 + 17 * k, own, LEVELS, (L, pl) => { (kits[L] ??= []).push(structuredClone(pl.s.equipment)); });
  for (const L of LEVELS) {
    const ref = typicalBuild(cls, L).save;
    const c: Cell = { cls, L, boss: bossFor(cls, L).name, ref: fight(ref, cls, L, 0), refScore: gearScore(ref), fights: [], scores: [], ilvl: [] };
    for (const eq of kits[L] ?? []) {
      const s = structuredClone(ref);
      s.equipment = structuredClone(eq);
      c.scores.push(gearScore(s));
      const worn = Object.entries(eq).filter(([k, x]) => x && !/^(ring|amulet)/.test(k)).map(([, x]) => x!.ilvl);
      c.ilvl.push(mean(worn));
      for (let f = 0; f < FIGHTS; f++) c.fights.push(fight(s, cls, L, f));
    }
    cells.push(c);
    const won = c.fights.filter((x) => x.won);
    if (!GATE) console.log(`${cls.padEnd(12)} L${String(L).padEnd(2)} ${c.boss.slice(0, 28).padEnd(28)} won ${won.length}/${c.fights.length} · TTK ${mean(won.map((x) => x.secs)).toFixed(0)}s (ref ${c.ref.won ? c.ref.secs.toFixed(0) + 's' : 'lost'}) · deaths ${mean(c.fights.map((x) => x.deaths)).toFixed(1)} · gear ${((mean(c.scores) / c.refScore - 1) * 100).toFixed(0)}% vs ref`);
  }
}

const wall = (c: Cell): string[] => {
  const won = c.fights.filter((x) => x.won), out: string[] = [];
  if (won.length * 3 < c.fights.length * 2) out.push(`wins ${won.length}/${c.fights.length}`);
  const t = mean(won.map((x) => x.secs));
  if (won.length && c.ref.won && t > 2 * c.ref.secs) out.push(`${(t / c.ref.secs).toFixed(1)}× the reference time`);
  if (won.length && t > WALL_SECS) out.push(`${t.toFixed(0)} s`);
  return out;
};
const md: string[] = ['# Boss check at typical gear', '', `Generated by tools/e2e/sim/boss-check.ts. Each boss fought ${SEEDS * FIGHTS}× (${SEEDS} gear-curve kits × ${FIGHTS} fight seeds) on the typical tree / hotbar, ` +
  `against the builds suite's typical gear as reference. Wall = wins < 2/3, or > 2× the reference time, or > ${WALL_SECS} s. Gear = gear-curve √(offence × EHP) vs the reference kit.`, ''];
const walls = cells.filter((c) => wall(c).length);
md.push('## Walls for a typical player', '', ...(walls.length ? walls.map((c) => `- **${c.cls} L${c.L} ${c.boss}**: ${wall(c).join(', ')}`) : ['- none']), '');
md.push('## Every fight', '', '| class | L | boss | wins | TTK (wins) | ref TTK | deaths | potions | HP left | gear vs ref | worn ilvl |', '|---|---|---|---|---|---|---|---|---|---|---|');
for (const c of cells) {
  const won = c.fights.filter((x) => x.won);
  md.push(`| ${c.cls} | ${c.L} | ${c.boss} | ${won.length}/${c.fights.length} | ${won.length ? mean(won.map((x) => x.secs)).toFixed(0) + ' s' : '—'} | ${c.ref.won ? c.ref.secs.toFixed(0) + ' s' : 'lost'} | ${mean(c.fights.map((x) => x.deaths)).toFixed(1)} | ${mean(c.fights.map((x) => x.potions)).toFixed(1)} | ${mean(c.fights.map((x) => x.hpLeft)).toFixed(0)}% | ${((mean(c.scores) / c.refScore - 1) * 100).toFixed(0)}% | ${mean(c.ilvl).toFixed(1)} |`);
}
for (const L of LEVELS) {
  const cs = cells.filter((c) => c.L === L), ws = cs.flatMap((c) => c.fights.filter((x) => x.won).map((x) => x.secs)).sort((a, b) => a - b);
  md.push('', `L${L}: ${cs.reduce((a, c) => a + c.fights.filter((x) => x.won).length, 0)}/${cs.reduce((a, c) => a + c.fights.length, 0)} won · median TTK ${ws[ws.length >> 1]?.toFixed(0) ?? '—'} s · gear ${((mean(cs.map((c) => mean(c.scores) / c.refScore)) - 1) * 100).toFixed(0)}% vs reference`);
}
mkdirSync('tools/e2e/out', { recursive: true });
writeFileSync('tools/e2e/out/boss-check.md', md.join('\n'));
console.log(`${walls.length} walls · report tools/e2e/out/boss-check.md · run time ${((Date.now() - t0) / 1000).toFixed(1)} s`);

// ───────────── gate ─────────────
if (GATE) {
  const all = cells.flatMap((c) => [c.ref, ...c.fights]);
  const crashes = all.filter((r) => r.crash);
  check(!crashes.length, `no crash in ${all.length} boss fights`, crashes.slice(0, 2).map((r) => r.crash).join(' || '));
  for (const L of LEVELS) {
    const cs = cells.filter((c) => c.L === L), lost = cs.filter((c) => c.fights.some((x) => !x.won)), died = cs.filter((c) => c.fights.some((x) => x.deaths > 0));
    check(!lost.length, `L${L} bosses (${BOSS_SLOT_NAME[L]}): every fight won at typical gear (${cs.length} classes)`, lost.map((c) => `${c.cls} ${c.boss}`).join(', '));
    check(!died.length, `L${L} bosses: 0 deaths`, died.map((c) => `${c.cls} ${c.boss}`).join(', '));
    const slow = cs.map((c) => ({ c, t: Math.max(0, ...c.fights.filter((x) => x.won).map((x) => x.secs)), cap: ALLOW[`${c.cls}:${c.L}`]?.secs ?? WALL_SECS })).filter((x) => x.t > x.cap);
    check(!slow.length, `L${L} bosses: every win ≤ ${WALL_SECS} s (or its allowance)`, slow.map((x) => `${x.c.cls} ${x.c.boss} ${x.t} s > ${x.cap} s`).join(', '));
  }
  const { checks, fails } = tally();
  if (fails) process.exitCode = 1;
  console.log(`${checks - fails}/${checks} passed`);
}
