// Builds the public-realm server (Node) with esbuild:
//   dist-server/main.mjs     the HTTP + WebSocket process
//   dist-server/realm.js     the realm bundle (IIFE) loaded into one vm context per realm
// The realm bundle is the game's own Phaser-free authority code (core, net, world, systems, narrative).
// A tiny plugin expands Vite's import.meta.glob (used by the content Registry) at build time.
import { build } from 'esbuild';
import { globSync, readFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const alias = { '@': join(root, 'src') };

/** import.meta.glob('<pattern>', { eager: true }) → { './x.ts': __g0, … } with static imports. */
const globPlugin = {
  name: 'import-meta-glob',
  setup(b) {
    b.onLoad({ filter: /\.(ts|js)$/ }, (args) => {
      let src = readFileSync(args.path, 'utf8');
      if (!src.includes('import.meta.glob')) return undefined;
      const dir = dirname(args.path);
      let n = 0;
      const imports = [];
      src = src.replace(/import\.meta\.glob(?:<[^>]*>)?\(\s*['"]([^'"]+)['"]\s*,\s*\{\s*eager:\s*true\s*\}\s*\)/g, (_m, pattern) => {
        const expanded = pattern.replace(/\{([^}]+)\}/, '@($1)').replace(/,/g, '|');
        const files = globSync(pattern.includes('{') ? pattern.replace(/\{([^}]+)\}/, (_, alts) => `{${alts}}`) : pattern, { cwd: dir });
        const entries = files.map((f) => {
          const id = `__glob${n++}`;
          const rel = './' + relative(dir, join(dir, f)).split('\\').join('/');
          imports.push(`import * as ${id} from ${JSON.stringify(rel)};`);
          return `${JSON.stringify(rel)}: ${id}`;
        });
        void expanded;
        return `({ ${entries.join(', ')} })`;
      });
      return { contents: imports.join('\n') + '\n' + src, loader: args.path.endsWith('.ts') ? 'ts' : 'js', resolveDir: dir };
    });
  },
};

const common = { bundle: true, alias, logLevel: 'info', plugins: [globPlugin], define: { 'import.meta.env.DEV': 'false', 'import.meta.env': '{"DEV":false}' } };

await build({ ...common, entryPoints: [join(root, 'server/realm-entry.ts')], outfile: join(root, 'dist-server/realm.js'), format: 'iife', platform: 'neutral', target: 'es2022', mainFields: ['module', 'main'] });
await build({ ...common, entryPoints: [join(root, 'server/main.ts')], outfile: join(root, 'dist-server/main.mjs'), format: 'esm', platform: 'node', target: 'node20', packages: 'external' });

// Make dist-server/ a self-contained, deployable folder: `gcloud run deploy --source dist-server` (small upload,
// and it doesn't depend on .gitignore, which excludes dist-server from a repo-root upload).
const { writeFileSync } = await import('node:fs');
writeFileSync(join(root, 'dist-server/package.json'), JSON.stringify({
  name: 'hollow-crown-realms', private: true, type: 'module', main: 'main.mjs', engines: { node: '>=22' },
  scripts: { start: 'node main.mjs' }, dependencies: { ws: '8.18.3', jose: '6.1.0' },
}, null, 2));
writeFileSync(join(root, 'dist-server/Dockerfile'), [
  '# Generated by server/build.mjs: deployable realm server (gcloud run deploy --source dist-server)',
  'FROM node:22-slim',
  'WORKDIR /app',
  'ENV NODE_ENV=production',
  'COPY package.json ./',
  'RUN npm install --omit=dev --no-audit --no-fund',
  'COPY main.mjs realm.js ./',
  'EXPOSE 8080',
  'CMD ["node", "main.mjs"]',
  '',
].join('\n'));
console.log('dist-server/ is deployable (package.json + Dockerfile written)');
