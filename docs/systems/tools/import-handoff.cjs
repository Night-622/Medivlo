#!/usr/bin/env node
/**
 * Generates src/data/**\/hc/*.gen.ts from the Claude Design handoff (Claude 3).
 * Usage: node docs/systems/tools/import-handoff.cjs
 * Runs the handoff's art/gear/bestiary/realms/legendary scripts in a stubbed VM (no canvas) and
 * slices CLASSES / SKSP / SKEL / SKKEY out of "Medival Screens.dc.html". Output is plain data;
 * the mechanics live in src/systems/rules.
 */
const fs = require('fs');
const vm = require('vm');
const path = require('path');

const ROOT = path.resolve(__dirname, '../../..');
const HO = path.join(ROOT, 'Medieval Browser Action RPG');
const OUT = (p) => path.join(ROOT, 'src/data', p);

// ---------- run the handoff scripts with a do-nothing DOM ----------
function stub() {
  const f = function () { return p; };
  const p = new Proxy(f, {
    get: (t, k) => {
      if (k === Symbol.toPrimitive) return () => 0;
      if (k === 'width' || k === 'height' || k === 'length') return 32;
      if (k === 'data') return new Uint8ClampedArray(32 * 32 * 4);
      if (k === 'then') return undefined;
      return p;
    },
    apply: () => p, construct: () => p, set: () => true,
  });
  return p;
}
const timers = [];
const win = {
  document: {
    createElement: stub, addEventListener() {}, querySelector: () => null, querySelectorAll: () => [], getElementById: () => null,
    fonts: { ready: Promise.resolve(), load: () => Promise.resolve([]), check: () => true, add() {} },
    body: stub(), head: stub(), documentElement: stub(),
  },
  setTimeout: (f) => { timers.push(f); return 1; }, clearTimeout() {}, requestAnimationFrame() {}, addEventListener() {},
  console, Math, JSON, Promise, Image: stub, OffscreenCanvas: stub, ImageData: stub,
  performance: { now: () => 0 }, localStorage: { getItem: () => null, setItem() {} }, navigator: {}, location: { search: '' },
};
win.window = win; win.globalThis = win; win.self = win;
const ctx = vm.createContext(win);
for (const f of ['art.js', 'tiles.js', 'gear.js', 'bestiary.js', 'map.js', 'realms.js', 'legendary.js']) {
  vm.runInContext(fs.readFileSync(path.join(HO, f), 'utf8'), ctx, { filename: f });
  for (let i = 0; i < 200 && timers.length; i++) for (const fn of timers.splice(0)) fn();
}
const MV = win.MV;
const G = MV.GEAR;

// ---------- slice the prototype's tables ----------
const html = fs.readFileSync(path.join(HO, 'Medival Screens.dc.html'), 'utf8');
function slice(name) {
  const start = html.indexOf(name + ' = ');
  if (start < 0) throw new Error('missing ' + name);
  let i = html.indexOf('=', start) + 1;
  while (html[i] === ' ') i++;
  const open = html[i], close = open === '[' ? ']' : '}';
  let depth = 0, str = null;
  for (let j = i; j < html.length; j++) {
    const c = html[j];
    if (str) { if (c === '\\') j++; else if (c === str) str = null; continue; }
    if (c === '\'' || c === '"' || c === '`') { str = c; continue; }
    if (c === open || c === '[' || c === '{') depth++;
    else if (c === close || c === ']' || c === '}') { depth--; if (depth === 0) return vm.runInNewContext('(' + html.slice(i, j + 1) + ')'); }
  }
  throw new Error('unterminated ' + name);
}
const CLASSES = slice('CLASSES'), SKSP = slice('SKSP'), SKEL = slice('SKEL'), SKKEY = slice('SKKEY');

// ---------- emit ----------
const HEAD = (src) => `/* GENERATED by docs/systems/tools/import-handoff.cjs from the handoff (${src}). Do not edit by hand. */\n`;
const J = (v) => JSON.stringify(v);
function write(rel, body) {
  fs.mkdirSync(path.dirname(OUT(rel)), { recursive: true });
  fs.writeFileSync(OUT(rel), body);
  console.log('wrote', rel, (body.length / 1024).toFixed(1) + ' KB');
}
const rows = (arr) => arr.map((x) => '  ' + J(x) + ',').join('\n');

// weapons
const MAT = G.MAT.map((m) => ({ id: m.id, name: m.name, rarity: m.rar }));
const WEAPONS = G.WEAPONS.map((w) => ({ id: w.id, type: w.type, material: w.mat.id, name: w.name, rarity: w.rar, dmg: w.dmg, ilvl: w.ilvl, value: w.val }));
write('items/hc/weapons.gen.ts', HEAD('gear.js') +
  `import type { HcMaterial, HcWeaponBase } from '@/systems/rules/types';\n\n` +
  `export const HC_MATERIALS: HcMaterial[] = ${J(MAT)};\n\n` +
  `export const HC_WEAPON_TYPES = ${J(G.WT)} as const;\n\n` +
  `export const HC_WEAPONS: HcWeaponBase[] = [\n${rows(WEAPONS)}\n];\n`);

// armour
const SETS = G.SETS.map((s) => ({
  id: s.id, school: s.school, style: s.style, name: s.name, helm: s.helm, rarity: s.rar, tier: s.tier, lore: s.lore,
  twoPiece: s.two, ability: s.ability, attuned: s.affinity, palette: { a: s.a, b: s.b, trim: s.t },
}));
const PIECES = G.PIECES.map((p) => ({ id: p.id, set: p.setId, piece: p.piece, slot: p.slot, name: p.name, rarity: p.rar, stats: p.st, ilvl: p.ilvl, value: p.val }));
write('items/hc/armour.gen.ts', HEAD('gear.js') +
  `import type { HcArmourPiece, HcArmourSet } from '@/systems/rules/types';\n\n` +
  `export const HC_SCHOOLS = ${J(G.SCH)} as const;\nexport const HC_STYLES = ${J(G.STY)} as const;\n\n` +
  `export const HC_SETS: HcArmourSet[] = [\n${rows(SETS)}\n];\n\n` +
  `export const HC_PIECES: HcArmourPiece[] = [\n${rows(PIECES)}\n];\n`);

// items + cosmetics
const ITEMS = G.ITEMS.map((i) => ({ id: i.id, cat: i.cat, name: i.name, rarity: i.rar, desc: i.desc, value: i.val }));
const kits = {};
for (const c of CLASSES) { try { kits[c.id] = G.kitOf(c.id); } catch { /* optional */ } }
write('items/hc/items.gen.ts', HEAD('gear.js') +
  `import type { HcItemBase } from '@/systems/rules/types';\n\n` +
  `export const HC_ITEM_CATS = ${J(G.CATS)} as const;\n\n` +
  `export const HC_ITEMS: HcItemBase[] = [\n${rows(ITEMS)}\n];\n\n` +
  `/** Accessory options per slot (cosmetic). */\nexport const HC_ACCESSORIES = ${J(G.ACC_N)};\n\n` +
  `/** Per-class allowed accessory option indexes + alt headwear (MV.GEAR.kitOf). */\nexport const HC_CLASS_COSMETICS: Record<string, { cape: number[]; neck: number[]; face: number[]; extra: number[]; alt: string }> = ${J(JSON.parse(J(kits)))};\n`);

// legendaries
const LG_BASES = ['w_sword_spark', 'w_axe_ember', 'w_staff_rime', 'w_bow_storm', 'w_mace_umbral', 'w_spear_spark', 'w_dagger_umbral', 'w_wand_storm', 'i_moonpend', 'i_sunpend', 'i_emberring', 'i_tear']; // legendary.js BASES
const LEG = MV.LEGENDARY.map((l, i) => ({ id: l.id, name: l.name, boss: l.boss, bossName: l.bossName, region: l.region, slot: l.slot, base: LG_BASES[i % LG_BASES.length], fx: l.fx, lore: l.lore, value: l.val }));
const FX = [...new Set(LEG.map((l) => l.fx))];
write('items/hc/legendary.gen.ts', HEAD('legendary.js') +
  `import type { HcLegendaryBase } from '@/systems/rules/types';\n\n` +
  `/** The six signature-effect texts, in handoff order (index = HcLegendaryBase.fxIndex). */\nexport const HC_LEGENDARY_FX = ${J(FX)};\n\n` +
  `export const HC_LEGENDARIES: HcLegendaryBase[] = [\n${rows(LEG.map((l) => ({ ...l, fxIndex: FX.indexOf(l.fx) })))}\n];\n`);

// bestiary
const BEASTS = MV.BESTIARY.map((b) => ({ id: b.id, name: b.name, tier: b.tier, arch: b.arch, scale: b.k, region: b.region, element: b.el, hp: b.hp, abilities: b.ab, drops: b.drops, lore: b.lore }));
const REALMS = MV.REALMDATA.RE.map((r) => ({ id: r.id, school: r.school ?? 'concord', name: r.name, capital: r.cap, landmark: r.lm, desc: r.desc }));
write('enemies/hc/bestiary.gen.ts', HEAD('bestiary.js + realms.js') +
  `import type { HcCreatureBase, HcRealmBase } from '@/systems/rules/types';\n\n` +
  `export const HC_BESTIARY: HcCreatureBase[] = [\n${rows(BEASTS)}\n];\n\n` +
  `export const HC_REALMS: HcRealmBase[] = [\n${rows(REALMS)}\n];\n`);

// classes + tree text
const KITS = CLASSES.map((c) => ({
  id: c.id, name: c.name, epithet: c.epithet, school: c.school, role: c.role, tags: c.tags, color: c.color,
  rating: { might: c.stats[0], guard: c.stats[1], arcana: c.stats[2], speed: c.stats[3] }, difficulty: c.diff, lore: c.lore,
  abilities: c.abilities.map(([icon, name, desc]) => ({ icon, name, desc })),
}));
write('classes/hc/classes.gen.ts', HEAD('Medival Screens.dc.html → CLASSES, SKSP, SKEL, SKKEY') +
  `import type { HcClassBase, SchoolId } from '@/systems/rules/types';\n\n` +
  `export const HC_CLASSES: HcClassBase[] = [\n${rows(KITS)}\n];\n\n` +
  `/** School spells for the Spells tree: [top 1, top 2, ultimate] as [name, desc]. */\n` +
  `export const HC_SCHOOL_SPELLS: Record<SchoolId, [string, string][]> = ${J(SKSP)};\n\n` +
  `/** School element node for the Skills tree: [name, desc]. */\nexport const HC_SCHOOL_ELEMENT: Record<SchoolId, [string, string]> = ${J(SKEL)};\n\n` +
  `/** Mutually exclusive school keystones for the Skills tree. */\nexport const HC_SCHOOL_KEYSTONES: Record<SchoolId, [string, string][]> = ${J(SKKEY)};\n`);

const ATLAS = JSON.parse(fs.readFileSync(path.join(HO, 'assets/atlas.json'), 'utf8'));
const LOOKS = Object.fromEntries(Object.entries(ATLAS.heroes).map(([id, h]) => [id, h.defaultLook]));
fs.appendFileSync(OUT('classes/hc/classes.gen.ts'), `\n/** atlas.heroes[*].defaultLook (option indexes into atlas.heroComposer.options; body 0 = Female, 1 = Male). */\nexport const HC_DEFAULT_LOOK: Record<string, { skin: number; hair: number; hc: number; eyes: number; ec: number; mouth: number; mark: number; body: number }> = ${J(LOOKS)};\n\n/** atlas.heroComposer.options */\nexport const HC_LOOK_OPTIONS = ${J(ATLAS.heroComposer.options)};\n`);
console.log(`weapons ${WEAPONS.length}, sets ${SETS.length}, pieces ${PIECES.length}, items ${ITEMS.length}, legendaries ${LEG.length}, creatures ${BEASTS.length}, realms ${REALMS.length}, classes ${KITS.length}`);
